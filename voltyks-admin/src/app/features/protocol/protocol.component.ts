import { Component, OnInit, ChangeDetectionStrategy } from '@angular/core';
import { CommonModule } from '@angular/common';
import { PrintService } from '../../core/services/print.service';

@Component({
  selector: 'app-protocol',
  standalone: true,
  imports: [CommonModule],
  templateUrl: './protocol.component.html',
  styleUrls: ['./protocol.component.scss'],
  changeDetection: ChangeDetectionStrategy.OnPush
})
export class ProtocolComponent implements OnInit {
  selectedType: 'chinese' | 'european' = 'chinese';

  constructor(private printService: PrintService) {}

  ngOnInit(): void {
    // Component initialized with hardcoded protocol content
  }

  toggleProtocolType(): void {
    this.selectedType = this.selectedType === 'chinese' ? 'european' : 'chinese';
  }

  get detailedContent(): string {
    if (this.selectedType === 'chinese') {
      return this.getChineseProtocolContent();
    } else {
      return this.getEuropeanProtocolContent();
    }
  }

  private getChineseProtocolContent(): string {
    return `🔵 البروتوكول الصيني لشحن السيارات الكهربائية — GB/T

📌 تعريفه:
البروتوكول الصيني، ويُعرف باسم GB/T (أو Guobiao)، هو معيار وطني صيني مُصمم خصيصًا لشحن السيارات الكهربائية. يتميز بمنافذ فريدة مختلفة عن النظم الأوروبية أو الأمريكية، وقد تم تطويره ليتماشى مع احتياجات السوق الصينية الضخمة للسيارات الكهربائية.

🚗 لماذا وُجد:
• تطوير معيار وطني مستقل يدعم الصناعة المحلية ويعزز الاستقلال التكنولوجي.
• توفير بنية تحتية متكاملة لشحن السيارات الكهربائية داخل الصين، التي تُعد أكبر سوق للسيارات الكهربائية عالميًا.
• دعم نمو الصناعات المحلية مثل BYD، NIO، Xpeng، وغيرها من الشركات الصينية الرائدة.

🔌 تكوين المنافذ:
يتكون النظام الصيني من نوعين رئيسيين من الموصلات:

1️⃣ GB/T AC (تيار متردد):
   • يُستخدم للشحن البطيء (3.3 kW - 7 kW).
   • يشبه في الشكل منافذ Type 2 الأوروبية لكنه غير متوافق معها.

2️⃣ GB/T DC (تيار مستمر):
   • يُستخدم للشحن السريع (يصل حتى 250 kW وأحيانًا أكثر).
   • يتميز بتصميم فريد مع دبوسين كبيرين للتيار المستمر ودبابيس إضافية للاتصال والسلامة.

📡 بروتوكول الاتصال:
• يعتمد البروتوكول الصيني على معيار اتصال مُحدد (مشابه لـ CAN Bus ولكن بمواصفات صينية).
• يتيح تبادل المعلومات بين المحطة والسيارة، مثل: حالة البطارية، معدل الشحن المطلوب، ودرجة الحرارة.
• يشمل آليات حماية متقدمة لضمان الأمان أثناء عملية الشحن.

🔐 مميزات السلامة:
• حماية من التيار الزائد (Overcurrent Protection).
• كشف الأعطال تلقائيًا وإيقاف الشحن في حالة الخطر.
• عزل كهربائي مُحكم لمنع حدوث صدمات.
• حماية ضد الحرارة الزائدة (Overheating Protection).

🌍 التوزيع الجغرافي:
• ينتشر بشكل أساسي في الصين وبعض الأسواق الآسيوية.
• بدأ بالانتشار في دول أخرى تستورد سيارات صينية (مثل تايلاند، وبعض دول جنوب شرق آسيا).
• غير مدعوم بشكل واسع خارج الصين بسبب اختلاف المعايير.

✅ المزايا:
• دعم كامل للسوق الصيني الضخم.
• سرعة شحن عالية في محطات DC.
• أمان عالٍ مع معايير صارمة للحماية.
• تكلفة إنتاج منخفضة نسبيًا بسبب التصنيع المحلي.

⚠️ التحديات:
• عدم التوافق مع المعايير العالمية الأخرى (CCS، CHAdeMO).
• صعوبة الشحن خارج الصين بدون محولات خاصة.
• محدودية انتشار محطات الشحن GB/T خارج آسيا.

🔮 المستقبل:
مع تزايد تصدير السيارات الكهربائية الصينية للعالم، قد نشهد محطات شحن متعددة المعايير تدعم GB/T بجانب CCS وCHAdeMO، لكن التوافقية تبقى تحديًا كبيرًا.`;
  }

  private getEuropeanProtocolContent(): string {
    return `🟢 البروتوكول الأوروبي لشحن السيارات الكهربائية — CCS2

📌 تعريفه:
CCS2 (Combined Charging System 2) هو المعيار الأوروبي الموحد لشحن السيارات الكهربائية. تم تطويره من قِبل اتحاد من الشركات الأوروبية والأمريكية، ويجمع بين موصلات التيار المتردد (AC) والتيار المستمر (DC) في منفذ واحد.

🚗 لماذا وُجد:
• توحيد معايير الشحن في أوروبا لتسهيل البنية التحتية.
• دعم الشحن البطيء (المنزلي) والسريع (محطات الطرق السريعة) بنفس الموصل.
• تقليل الحاجة لمحولات أو موصلات متعددة.
• تشجيع انتشار السيارات الكهربائية من خلال توحيد التقنية.

🔌 تكوين المنافذ:
يتكون CCS2 من منفذ مُدمج يحتوي على:

1️⃣ Type 2 AC (تيار متردد):
   • الجزء العلوي من الموصل (5 دبابيس).
   • يُستخدم للشحن البطيء في المنازل أو محطات العمل (3.7 kW - 22 kW).

2️⃣ DC Pins (تيار مستمر):
   • دبوسان إضافيان في الأسفل.
   • يُستخدمان للشحن السريع (50 kW - 350 kW).
   • يدعم تقنيات مثل Ionity و Tesla Supercharger (النسخة الأوروبية).

📡 بروتوكول الاتصال:
• يعتمد على معيار ISO 15118، وهو بروتوكول اتصال متقدم بين المحطة والسيارة.
• يدعم:
  - Plug & Charge: توصيل وشحن تلقائي بدون الحاجة لبطاقة أو تطبيق.
  - Smart Charging: تنظيم استهلاك الطاقة بناءً على الشبكة.
  - Vehicle-to-Grid (V2G): إعادة ضخ الطاقة من السيارة للشبكة.
• يتبادل معلومات مثل: مستوى البطارية، الطاقة المطلوبة، حالة الشحن، ودرجة الحرارة.

🔐 مميزات السلامة:
• حماية من التيار الزائد والجهد الزائد.
• آلية قفل ميكانيكية للموصل أثناء الشحن.
• عزل كهربائي محكم لمنع الصدمات.
• مراقبة مستمرة لدرجة الحرارة والتيار.
• إيقاف تلقائي في حالة اكتشاف أي خلل.

🌍 التوزيع الجغرافي:
• المعيار الرسمي في جميع دول الاتحاد الأوروبي.
• مدعوم في:
  - أوروبا بالكامل
  - أستراليا ونيوزيلندا
  - بعض دول آسيا (كوريا الجنوبية، الهند)
  - الشرق الأوسط (بما في ذلك السعودية والإمارات)
• تتبناه Tesla في أوروبا لمحطات Supercharger الجديدة.

✅ المزايا:
• توحيد معيار عالمي واسع الانتشار.
• سرعة شحن عالية جدًا (حتى 350 kW).
• دعم الشحن الذكي وV2G.
• توافق كبير مع معظم السيارات الكهربائية الحديثة.
• بنية تحتية قوية ومنتشرة في أوروبا.

⚠️ التحديات:
• غير مدعوم في السوق الأمريكي (يستخدمون CCS1).
• غير متوافق مع GB/T الصيني أو CHAdeMO الياباني بدون محولات.
• تكلفة بناء محطات الشحن السريع عالية نسبيًا.

🔮 المستقبل:
CCS2 يُعتبر المعيار المستقبلي في أوروبا والعديد من الأسواق العالمية. مع تبني Tesla وكبار المصنعين له، سيصبح المعيار الأكثر شيوعًا خلال السنوات القادمة، خصوصًا مع تطور تقنيات الشحن فائق السرعة (Mega Charging) التي قد تصل لـ 1 MW.`;
  }

  formatDate(dateString: string): string {
    if (!dateString) return '-';
    return new Date(dateString).toLocaleDateString('ar-EG', {
      year: 'numeric',
      month: 'long',
      day: 'numeric'
    });
  }

  get protocolTypeLabel(): string {
    return this.selectedType === 'chinese' ? 'البروتوكول الصيني' : 'البروتوكول الأوروبي';
  }

  get otherProtocolTypeLabel(): string {
    return this.selectedType === 'chinese' ? 'البروتوكول الأوروبي' : 'البروتوكول الصيني';
  }

  get protocolTypeIcon(): string {
    return this.selectedType === 'chinese' ? '🇨🇳' : '🇪🇺';
  }

  printToPdf(): void {
    const content = this.detailedContent.replace(/\n/g, '<br>');
    this.printService.printContentToPdf(content, {
      title: this.protocolTypeLabel,
      filename: this.selectedType === 'chinese' ? 'chinese_protocol' : 'european_protocol',
      orientation: 'portrait'
    });
  }
}
